/// 用中文词表做格式化：先查表，再按顺序用 Display 替换 `{}`。
/// 不用 `format!`，因为它的首参必须是字面量，而这里首参是运行时查表结果。
#[macro_export]
macro_rules! tr_fmt {
    ($src:expr $(, $arg:expr)* $(,)?) => {{
        let mut __s: String = $crate::i18n::tr($src).to_string();
        $(
            __s = __s.replacen("{}", &::std::string::ToString::to_string(&$arg), 1);
        )*
        __s
    }};
}
